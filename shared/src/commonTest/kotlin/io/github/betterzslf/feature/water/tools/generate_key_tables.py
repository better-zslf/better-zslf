"""Regenerate only WaterKeyTables.kt from the supplied, unmodified WAT source.

Usage: python generate_key_tables.py PATH_TO_UPSTREAM/src/deputy.wat OUTPUT.kt
No downloads, execution of upstream instructions, or binary analysis is involved.
"""
from pathlib import Path
import hashlib
import re
import sys

source = Path(sys.argv[1]).read_text(encoding="utf-8")
data = source.split("(data (i32.const 0)", 1)[1].split(";; 2096 bytes", 1)[0]
hex_bytes = re.findall(r"\\([0-9a-fA-F]{2})", data)
assert len(hex_bytes) == 2096, len(hex_bytes)
raw = bytes(int(value, 16) for value in hex_bytes)
rows = [raw[i:i + 16].hex() for i in range(0, len(raw), 16)]
body = " +\n".join('        "' + row + '"' for row in rows)
content = '''/*
 * Exact 2096-byte data segment of waterctl src/deputy.wat (MIT).
 * Copyright (c) 2021-2024 celesWuff, Deputy
 * See licenses/waterctl-MIT.txt.
 * Generated by commonTest/.../water/tools/generate_key_tables.py.
 * Data SHA-256: %s
 */
package io.github.betterzslf.feature.water

internal object WaterKeyTables {
    // Offsets: 0,256,512; a 16-byte table at 768; 784,1040,1296,1552;
    // overlapping output lookup regions: 1808,1938,1952,2082.
    private val hex =
%s

    private val data = IntArray(2096) { index ->
        (hex[index * 2].digitToInt(16) shl 4) or hex[index * 2 + 1].digitToInt(16)
    }

    operator fun get(index: Int): Int = data[index]
}
''' % (hashlib.sha256(raw).hexdigest(), body)
Path(sys.argv[2]).parent.mkdir(parents=True, exist_ok=True)
Path(sys.argv[2]).write_text(content, encoding="utf-8")
print("Generated", sys.argv[2], "2096 bytes; sha256=" + hashlib.sha256(raw).hexdigest())
